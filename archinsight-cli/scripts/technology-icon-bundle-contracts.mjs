import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

const entry = readFileSync(path.resolve('build/index.js'), 'utf8');
const chunksDirectory = path.resolve('build/chunks');
const chunks = readdirSync(chunksDirectory).filter((name) => name.endsWith('.js'));
const assetChunks = chunks.filter((name) => {
  const source = readFileSync(path.join(chunksDirectory, name), 'utf8');
  return source.includes('var icons =') && source.includes('currentColor');
});

assert(statSync(path.resolve('build/index.js')).size < 3_500_000, 'CLI entry must not eagerly bundle the SVG catalog');
assert.doesNotMatch(entry, /Generated by import-devicon\.mjs/);
assert.equal(assetChunks.length, 26, 'technology icon assets must remain split into one lazy chunk per alphabetic bucket');

console.log('technology icon bundle contracts passed');
