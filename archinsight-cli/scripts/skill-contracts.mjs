import assert from "node:assert/strict";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(cliRoot, "..");
const cliEntrypoint = path.join(cliRoot, "build", "index.js");
const temporaryRoot = mkdtempSync(path.join(os.tmpdir(), "archinsight-skill-contracts-"));

try {
  const generated = new Map();
  for (const target of ["generic", "codex", "claude"]) {
    const output = path.join(temporaryRoot, target);
    runCli(["skill", "init", repositoryRoot, "--target", target, "--out", output]);
    generated.set(target, output);
    verifyEntrypoint(target, output);
    verifySharedFiles(output);
  }

  const codexOutput = generated.get("codex");
  assert(codexOutput);
  verifyExamples(codexOutput);
  verifyC4RecipeAndJsonContract(codexOutput);
  console.log("agent skill contract fixtures passed");
} finally {
  rmSync(temporaryRoot, { recursive: true, force: true });
}

function runCli(args) {
  const result = spawnSync(process.execPath, [cliEntrypoint, ...args], {
    cwd: repositoryRoot,
    encoding: "utf8",
  });
  assert.equal(
    result.status,
    0,
    `archinsight ${args.join(" ")} failed\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`,
  );
  return result.stdout;
}

function verifyEntrypoint(target, output) {
  const entrypoint = path.join(output, target === "generic" ? "archinsight.md" : "SKILL.md");
  const content = readFileSync(entrypoint, "utf8");
  assert.equal(occurrences(content, "## Reference routing"), 1, `${target} must contain one reference routing section`);
  assert.equal(occurrences(content, "references/modeling.md"), 1, `${target} must route to modeling once`);
  assert.match(content, /generated by Archinsight CLI \d+\.\d+\.\d+/);
  assert(content.includes("archinsight query ... --format json"));
}

function verifySharedFiles(output) {
  const expectedBuiltin = readFileSync(
    path.join(repositoryRoot, "src", "main", "resources", "com", "github", "lonelylockley", "insight", "builtin-views", "c4.aiq"),
    "utf8",
  );
  const bundledBuiltin = readFileSync(path.join(output, "examples", "builtin-views", "c4.aiq"), "utf8");
  assert.equal(bundledBuiltin, expectedBuiltin);

  const recipe = readFileSync(path.join(output, "examples", "queries", "c4-internal-actors.aiq"), "utf8");
  assert(recipe.includes("OR node IS Actor"));
  assert(recipe.includes("deploymentTarget:InfrastructureComponent"));
  assert(recipe.includes("projectedPathSource:DeploymentElement"));
  assert(recipe.includes("incomingProjectedLink {projected}"));

}

function verifyExamples(output) {
  const examples = path.join(output, "examples");
  for (const name of ["layered-architecture.ai", "c1-context.ai", "c2-containers.ai", "c3-components.ai"]) {
    runCli(["link", path.join(examples, name), "--format", "text"]);
  }

  const c4Project = copyC4Project(examples, "c4-project");
  runCli(["link", c4Project, "--format", "text"]);
  runCli(["link", path.join(examples, "c4-private-gateway"), "--format", "text"]);
}

function verifyC4RecipeAndJsonContract(output) {
  const examples = path.join(output, "examples");
  const project = copyC4Project(examples, "c4-internal-actor-project");
  const modelPath = path.join(project, "c4-deployment.ai");
  const model = readFileSync(modelPath, "utf8").replace("external actor shopper", "actor shopper");
  writeFileSync(modelPath, model);

  const query = path.join(examples, "queries", "c4-internal-actors.aiq");
  const stdout = runCli([
    "query",
    project,
    "--context",
    "deployment_shop",
    "--source",
    "c4-deployment.ai",
    "--query",
    query,
    "--format",
    "json",
  ]);
  const graph = JSON.parse(stdout);

  assert.equal(graph.context, "deployment_shop");
  assert.equal(Array.isArray(graph.elements), false);
  assert(graph.elements["deployment_shop/shopper"]);
  assert(Array.isArray(graph.edges));
  assert(Array.isArray(graph.groups));
  assert(Array.isArray(graph.externalElements));

  const projected = graph.edges.filter((item) => item.edge?.projected === true);
  assert(projected.length > 0);
  assert(projected.some((item) => item.edge.originSource && item.edge.originTarget));
  assert(projected.every((item) => item.source === item.edge.source && item.target === item.edge.target));
}

function copyC4Project(examples, directoryName) {
  const target = path.join(temporaryRoot, directoryName);
  mkdirSync(target, { recursive: true });
  for (const name of ["c4-deployment-framework.ai", "c4-deployment-infrastructure.ai", "c4-deployment.ai"]) {
    copyFileSync(path.join(examples, name), path.join(target, name));
  }
  return target;
}

function occurrences(value, needle) {
  return value.split(needle).length - 1;
}
