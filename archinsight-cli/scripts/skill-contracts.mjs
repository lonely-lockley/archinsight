const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(cliRoot, "..");
const cliEntrypoint = path.join(cliRoot, "build", "index.js");
const temporaryRoot = mkdtempSync(path.join(os.tmpdir(), "archinsight-skill-contracts-"));

try {
  const generated = new Map();
  for (const target of ["generic", "codex", "claude"]) {
    const output = path.join(temporaryRoot, target);
    runCli(["skill", "init", repositoryRoot, "--target", target, "--out", output]);
    generated.set(target, output);
    verifyEntrypoint(target, output);
    verifySharedFiles(output);
  }

  const genericOutput = generated.get("generic");
  assert(genericOutput);
  verifySkillInitReplacementContract(genericOutput);

  const codexOutput = generated.get("codex");
  assert(codexOutput);
  verifyExamples(codexOutput);
  verifyC4CodeContract(codexOutput);
  verifyDeploymentRecipeAndJsonContract(codexOutput);
  verifyDeploymentProjectionContracts(codexOutput);
  console.log("agent skill contract fixtures passed");
} finally {
  rmSync(temporaryRoot, { recursive: true, force: true });
}

function runCli(args) {
  const result = spawnSync(process.execPath, [cliEntrypoint, ...args], {
    cwd: repositoryRoot,
    encoding: "utf8",
  });
  assert.equal(
    result.status,
    0,
    `archinsight ${args.join(" ")} failed\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`,
  );
  return result.stdout;
}

