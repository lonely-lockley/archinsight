function verifySkillInitReplacementContract(output) {
  const missingGeneratedFile = path.join(output, "references", "cli.md");
  rmSync(missingGeneratedFile);

  const refused = spawnSync(process.execPath, [
    cliEntrypoint,
    "skill",
    "init",
    repositoryRoot,
    "--target",
    "generic",
    "--out",
    output,
  ], {
    cwd: repositoryRoot,
    encoding: "utf8",
  });
  assert.notEqual(refused.status, 0);
  assert.match(refused.stderr, /Refusing to initialize skill because output directory .* already exists/);
  assert.equal(existsSync(missingGeneratedFile), false, "refused init must not modify a partial existing package");

  const staleFile = path.join(output, "stale-user-file.md");
  writeFileSync(staleFile, "must be removed by complete replacement\n");
  runCli([
    "skill",
    "init",
    repositoryRoot,
    "--target",
    "generic",
    "--out",
    output,
    "--force",
  ]);
  assert.equal(existsSync(missingGeneratedFile), true);
  assert.equal(existsSync(staleFile), false, "--force must replace the complete package");
  verifyEntrypoint("generic", output);
  verifySharedFiles(output);
}

function verifyExamples(output) {
  const examples = path.join(output, "examples");
  for (const name of ["layered-architecture.ai", "c1-context.ai", "c2-containers.ai", "c3-components.ai"]) {
    runCli(["link", path.join(examples, name), "--format", "text"]);
  }

  const deploymentProject = copyDeploymentProject(examples, "deployment-project");
  runCli(["link", deploymentProject, "--format", "text"]);
  runCli(["link", path.join(examples, "deployment-private-gateway"), "--format", "text"]);
  runCli(["link", path.join(examples, "c4-code"), "--format", "text"]);
}

function verifyC4CodeContract(output) {
  const project = path.join(output, "examples", "c4-code");
  const definitions = readFileSync(path.join(project, "definitions.ai"), "utf8");
  const model = readFileSync(path.join(project, "model.ai"), "utf8");
  assert.match(definitions, /extend type Component\s+List of CodeElement _/);
  assert.equal(definitions.includes("List of CodeElement code"), false);
  assert.doesNotMatch(model, /^\s+code:/m);
  assert.match(model, /component order_processing[\s\S]*?module controller/);

  const graph = JSON.parse(runCli([
    "query",
    project,
    "--context",
    "code_sample",
    "--source",
    "model.ai",
    "--view",
    "c4",
    "--format",
    "json",
  ]));

  assert(graph.elements["code_sample/controller"]);
  assert(graph.elements["code_sample/domain"]);
  assert(graph.elements["code_sample/validation"]);
  assert.equal(graph.elements["code_sample/order_processing"], undefined);
  assert(graph.edges.some((item) => item.source === "code_sample/controller" && item.target === "code_sample/domain"));
}

function verifyDeploymentRecipeAndJsonContract(output) {
  const examples = path.join(output, "examples");
  const project = copyDeploymentProject(examples, "deployment-internal-actor-project");
  const modelPath = path.join(project, "deployment.ai");
  const model = readFileSync(modelPath, "utf8").replace("external actor shopper", "actor shopper");
  writeFileSync(modelPath, model);

  const builtinGraph = JSON.parse(runCli([
    "query",
    project,
    "--context",
    "deployment_shop",
    "--source",
    "deployment.ai",
    "--view",
    "deployment",
    "--format",
    "json",
  ]));
  assert.equal(builtinGraph.context, "deployment_shop");
  assert.equal(Array.isArray(builtinGraph.edges), true);

  const query = path.join(examples, "queries", "deployment-internal-actors.aiq");
  const stdout = runCli([
    "query",
    project,
    "--context",
    "deployment_shop",
    "--source",
    "deployment.ai",
    "--query",
    query,
    "--format",
    "json",
  ]);
  const graph = JSON.parse(stdout);

  assert.equal(graph.context, "deployment_shop");
  assert.equal(Array.isArray(graph.elements), false);
  assert(graph.elements["deployment_shop/shopper"]);
  assert(Array.isArray(graph.edges));
  assert(Array.isArray(graph.groups));
  assert(Array.isArray(graph.externalElements));

  const projected = graph.edges.filter((item) => item.edge?.projected === true);
  assert(projected.length > 0);
  assert(projected.some((item) => item.edge.originSource && item.edge.originTarget));
  assert(projected.every((item) => item.source === item.edge.source && item.target === item.edge.target));
}

function copyDeploymentProject(examples, directoryName) {
  const target = path.join(temporaryRoot, directoryName);
  mkdirSync(target, { recursive: true });
  for (const name of ["deployment-framework.ai", "deployment-infrastructure.ai", "deployment.ai"]) {
    copyFileSync(path.join(examples, name), path.join(target, name));
  }
  return target;
}

function occurrences(value, needle) {
  return value.split(needle).length - 1;
}
