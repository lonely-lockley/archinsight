import { mkdir, readdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(scriptDirectory, "..");
const resourcesRoot = path.join(cliRoot, "src", "skill", "resources");
const manifestFile = path.join(resourcesRoot, "manifest.json");
const outputFile = path.join(cliRoot, "src", "generated", "skill-resources.ts");

const manifest = JSON.parse(await readFile(manifestFile, "utf8"));
assertManifest(manifest);

const resourcePaths = [
  ...(await filesUnder(manifest.sharedRoot)),
  ...await Promise.all(Object.values(manifest.targets).map((target) => filesUnder(target.resourceRoot))),
].flat().sort();
const uniquePaths = new Set(resourcePaths);
if (uniquePaths.size !== resourcePaths.length) {
  throw new Error("Skill resource manifest resolves the same resource more than once");
}

const resources = Object.fromEntries(await Promise.all(resourcePaths.map(async (resourcePath) => [
  resourcePath,
  await readFile(path.join(resourcesRoot, resourcePath), "utf8"),
])));
const generated = `// Generated by scripts/generate-skill-resources.mjs. Do not edit.\n\n`
  + `export const SKILL_RESOURCE_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n\n`
  + `export const SKILL_RESOURCES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(resources, null, 2)});\n`;

await mkdir(path.dirname(outputFile), { recursive: true });
const temporaryFile = `${outputFile}.tmp`;
await writeFile(temporaryFile, generated);
await rename(temporaryFile, outputFile);

async function filesUnder(relativeRoot) {
  const absoluteRoot = path.join(resourcesRoot, relativeRoot);
  const result = [];
  await visit(absoluteRoot, relativeRoot, result);
  return result;
}

async function visit(absoluteDirectory, relativeDirectory, result) {
  const entries = await readdir(absoluteDirectory, { withFileTypes: true });
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const absolutePath = path.join(absoluteDirectory, entry.name);
    const relativePath = path.posix.join(relativeDirectory.replaceAll(path.sep, "/"), entry.name);
    if (entry.isDirectory()) {
      await visit(absolutePath, relativePath, result);
    } else if (entry.isFile()) {
      result.push(relativePath);
    } else {
      throw new Error(`Unsupported skill resource '${relativePath}'`);
    }
  }
}

function assertManifest(value) {
  if (value?.schemaVersion !== "archinsight-skill-resources.v1" || typeof value.sharedRoot !== "string") {
    throw new Error("Unsupported skill resource manifest");
  }
  for (const target of ["generic", "codex", "claude"]) {
    const definition = value.targets?.[target];
    if (typeof definition?.defaultOutput !== "string"
      || typeof definition?.entrypoint !== "string"
      || typeof definition?.installedByDefault !== "boolean"
      || typeof definition?.resourceRoot !== "string") {
      throw new Error(`Invalid skill resource target '${target}'`);
    }
  }
}
